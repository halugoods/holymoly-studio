#!/usr/bin/env python3
"""
Holymoly Studio - Headless Flutter Dart-to-Pixel Capture Engine
(by Halu Goods Indonesia)

Compiles and renders ANY Flutter Dart widget or screen headlessly (no emulator/device needed),
loading real project fonts (SF-Pro) and disk assets, and capturing a ground-truth PNG.
Allows the AI agent to visually inspect Flutter UI with ZERO hallucination.
"""

import os
import subprocess
import sys
from pathlib import Path

DEFAULT_OUTPUT_DIR = Path("C:/Users/ertyui/ZCodeProject/holymoly_studio/assets/ui_captures")


def capture_widget(
    flutter_project_dir: str | Path,
    widget_import: str,
    widget_instantiation: str,
    output_filename: str = "captured_ui.png",
    width: int = 412,
    height: int = 220,
    dpr: float = 2.0,
    background_color: str = "0xFFF3EADB",
) -> Path:
    flutter_dir = Path(flutter_project_dir).resolve()
    test_dir = flutter_dir / "test"
    test_dir.mkdir(parents=True, exist_ok=True)
    DEFAULT_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    output_path = (DEFAULT_OUTPUT_DIR / output_filename).resolve()
    output_path_str = str(output_path).replace("\\", "/")

    # Auto-generate headless test file
    test_code = f"""// AUTO-GENERATED BY HOLYMOLY STUDIO FLUTTER RENDERER
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;
import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
{widget_import}

class DiskAssetBundle extends CachingAssetBundle {{
  @override
  Future<ByteData> load(String key) async {{
    final file = File(key);
    if (file.existsSync()) {{
      return ByteData.view(file.readAsBytesSync().buffer);
    }}
    final assetFile = File('assets/$key');
    if (assetFile.existsSync()) {{
      return ByteData.view(assetFile.readAsBytesSync().buffer);
    }}
    return rootBundle.load(key);
  }}
}}

Future<void> loadCustomFonts() async {{
  final studioFontDir = Directory('C:/Users/ertyui/ZCodeProject/holymoly_studio/assets/fonts');
  if (!studioFontDir.existsSync()) return;

  // 1. Material Icons
  final matFile = File('C:/Users/ertyui/ZCodeProject/holymoly_studio/assets/fonts/MaterialIcons-Regular.otf');
  if (matFile.existsSync()) {{
    final loader = FontLoader('MaterialIcons');
    loader.addFont(Future.value(ByteData.view(matFile.readAsBytesSync().buffer)));
    await loader.load();
  }}

  // 2. Cupertino Icons
  final cupFile = File('C:/Users/ertyui/ZCodeProject/holymoly_studio/assets/fonts/CupertinoIcons.ttf');
  if (cupFile.existsSync()) {{
    final l1 = FontLoader('CupertinoIcons');
    final l2 = FontLoader('packages/cupertino_icons/CupertinoIcons');
    l1.addFont(Future.value(ByteData.view(cupFile.readAsBytesSync().buffer)));
    l2.addFont(Future.value(ByteData.view(cupFile.readAsBytesSync().buffer)));
    await l1.load();
    await l2.load();
  }}

  // 3. Typography Fonts (Plus Jakarta Sans, SF-Pro, Inter, Poppins, Roboto)
  final fontFamilies = [
    'SF-Pro',
    'Plus Jakarta Sans',
    'PlusJakartaSans',
    'plusJakartaSans',
    'plusJakartaSans_regular',
    'plusJakartaSans_bold',
    'plusJakartaSans_medium',
    'plusJakartaSans_semibold',
    'Roboto',
    'Inter',
    'Poppins',
  ];

  final interFile = File('C:/Users/ertyui/ZCodeProject/holymoly_studio/assets/fonts/Inter.ttf');
  if (interFile.existsSync()) {{
    final bytes = interFile.readAsBytesSync().buffer;
    for (final fam in fontFamilies) {{
      try {{
        final loader = FontLoader(fam);
        loader.addFont(Future.value(ByteData.view(bytes)));
        await loader.load();
      }} catch (_) {{}}
    }}
  }}
}}

void main() {{
  setUpAll(() async {{
    TestWidgetsFlutterBinding.ensureInitialized();
    await loadCustomFonts();
  }});

  testWidgets('Holymoly Headless Dart Render', (WidgetTester tester) async {{
    tester.view.physicalSize = const Size({width} * {dpr}, {height} * {dpr});
    tester.view.devicePixelRatio = {dpr};
    addTearDown(() => tester.view.resetPhysicalSize());

    final GlobalKey repaintKey = GlobalKey();

    await tester.pumpWidget(
      DefaultAssetBundle(
        bundle: DiskAssetBundle(),
        child: MaterialApp(
          debugShowCheckedModeBanner: false,
          theme: ThemeData(
            fontFamily: 'SF-Pro',
            scaffoldBackgroundColor: const Color({background_color}),
          ),
          home: Scaffold(
            backgroundColor: const Color({background_color}),
            body: Center(
              child: RepaintBoundary(
                key: repaintKey,
                child: SizedBox(
                  width: {width}.0,
                  child: {widget_instantiation},
                ),
              ),
            ),
          ),
        ),
      ),
    );

    // Precache all local image assets
    await tester.runAsync(() async {{
      final element = repaintKey.currentContext!;
      final assetDir = Directory('assets');
      if (assetDir.existsSync()) {{
        for (final f in assetDir.listSync(recursive: true).whereType<File>()) {{
          final p = f.path.replaceAll('\\\\', '/');
          if (p.endsWith('.png') || p.endsWith('.jpg') || p.endsWith('.jpeg') || p.endsWith('.webp')) {{
            try {{
              await precacheImage(AssetImage(p), element);
            }} catch (_) {{}}
          }}
        }}
      }}
    }});

    await tester.pump();
    await tester.pump(const Duration(milliseconds: 300));

    final RenderRepaintBoundary boundary =
        repaintKey.currentContext!.findRenderObject()! as RenderRepaintBoundary;
    final ui.Image image = await boundary.toImage(pixelRatio: {dpr});
    final ByteData? byteData =
        await image.toByteData(format: ui.ImageByteFormat.png);
    final Uint8List pngBytes = byteData!.buffer.asUint8List();

    File('{output_path_str}').writeAsBytesSync(pngBytes);
    print('CAPTURE_COMPLETE: {output_path_str} (${{pngBytes.length}} bytes)');
  }});
}}
"""

    gen_test_path = test_dir / "_holymoly_render_test.dart"
    gen_test_path.write_text(test_code, encoding="utf-8")

    print(f"[Holymoly Flutter Renderer] Compiling & rendering widget headlessly...")
    cmd = ["flutter.bat" if os.name == "nt" else "flutter", "test", "--no-pub", f"test/{gen_test_path.name}"]
    res = subprocess.run(cmd, cwd=str(flutter_dir), capture_output=True, text=True, timeout=30)

    if res.returncode != 0:
        print("[Holymoly Flutter Renderer] Error during test execution:")
        print(res.stderr or res.stdout)
        raise RuntimeError(f"Flutter headless render failed with code {res.returncode}")

    if not output_path.exists():
        raise FileNotFoundError(f"Expected output {output_path} was not created.")

    print(f"[Holymoly Flutter Renderer] SUCCESS -> {output_path}")
    return output_path


if __name__ == "__main__":
    # Test capture of Pay() widget in gage-preview
    out = capture_widget(
        flutter_project_dir="C:/Users/ertyui/ZCodeProject/gage-preview",
        widget_import="import 'package:gage_app/ui/home/components/gopay.dart';",
        widget_instantiation="Pay()",
        output_filename="gopay_card_master.png",
        width=412,
        height=220,
        dpr=2.0,
    )
    print(f"Captured to: {out}")
